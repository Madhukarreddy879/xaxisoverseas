import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const blogFile = path.join(root, 'src', 'data', 'blogPosts.ts');
const redirectsFile = path.join(root, 'public', '_redirects');

const staticPaths = [
  '/study-in-uk',
  '/universities',
  '/services',
  '/eligibility',
  '/blog',
  '/about',
  '/contact',
];

const source = fs.readFileSync(blogFile, 'utf8');
const blogSlugs = [...source.matchAll(/^\s*slug:\s*'([a-z0-9-]+)'/gm)].map((m) => m[1]);

if (blogSlugs.length === 0) {
  throw new Error('sync-redirects: no blog slugs found in src/data/blogPosts.ts');
}

const allRoutes = [...staticPaths, ...blogSlugs.map((s) => `/blog/${s}`)];
const lines = [
  '# Auto-generated by scripts/sync-redirects.mjs (runs on prebuild)',
  '/index.html / 301',
  ...allRoutes.map((r) => `${r} ${r}/ 301`),
  ...allRoutes.map((r) => `${r}/index.html ${r}/ 301`),
  '',
];

const nextContent = lines.join('\n');
const prevContent = fs.existsSync(redirectsFile) ? fs.readFileSync(redirectsFile, 'utf8') : '';

if (prevContent !== nextContent) {
  fs.writeFileSync(redirectsFile, nextContent, 'utf8');
  console.log(`sync-redirects: updated public/_redirects (${allRoutes.length} routes, ${lines.length - 2} rules)`);
} else {
  console.log(`sync-redirects: public/_redirects up to date (${allRoutes.length} routes)`);
}
